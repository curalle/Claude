INK, RED, SKIN = "#1d1b18", "#e0452b", "#e9b496"


def figure(prefix, markers):
    """Front-view body outline plus pulsing markers with leader lines to labels.

    markers: [(id, (mx, my), (lx, ly, side), label)] — label box anchored at lx,ly.
    """
    body = f"""
            <g fill="{SKIN}" stroke="{INK}" stroke-width="5">
              <rect x="392" y="735" width="44" height="275" rx="22" />
              <rect x="644" y="735" width="44" height="275" rx="22" />
              <rect x="452" y="970" width="80" height="210" rx="30" />
              <rect x="548" y="970" width="80" height="210" rx="30" />
              <rect x="440" y="722" width="200" height="268" rx="44" />
              <rect x="515" y="694" width="50" height="40" rx="10" />
              <circle cx="540" cy="648" r="58" />
            </g>"""
    marks, labels = [], []
    for mid, (mx, my), (lx, ly, side), text in markers:
        # leader goes from the marker to the label's near edge
        edge = lx
        marks.append(f"""
            <g id="{prefix}-{mid}">
              <line x1="{mx}" y1="{my}" x2="{edge}" y2="{ly + 26}" stroke="{INK}" stroke-width="4" stroke-dasharray="2 9" stroke-linecap="round" />
              <circle class="pulse" cx="{mx}" cy="{my}" r="22" fill="none" stroke="{RED}" stroke-width="5" />
              <circle cx="{mx}" cy="{my}" r="17" fill="{RED}" stroke="{INK}" stroke-width="4" />
            </g>""")
        pos = f"left: {lx}px" if side == "r" else f"right: {1080 - lx}px"
        labels.append(f'<div class="figlbl" id="{prefix}-{mid}-l" style="{pos}; top: {ly}px">{text}</div>')
    svg = f'<svg class="art" viewBox="0 0 1080 1920">{body}{"".join(marks)}\n          </svg>'
    return svg + "\n          " + "\n          ".join(labels)


