def scene(sid, start, dur, kicker, inner):
    return f"""
      <div id="{sid}" class="scene clip" data-start="{start}" data-duration="{dur}" data-track-index="6">
        <div class="wipe"></div>
        <div class="panel">
          <div class="kick"><span>{kicker}</span><span class="rule"></span></div>
          {inner}
        </div>
      </div>
"""


def mark(text, mid=""):
    i = f' id="{mid}"' if mid else ""
    return f'<span class="mark"{i}><span class="bar"></span><span class="t">{text}</span></span>'


