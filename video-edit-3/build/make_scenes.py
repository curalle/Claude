def mark(text, mid=""):
    i = f' id="{mid}"' if mid else ""
    return f'<span class="mark"{i}><span class="bar"></span><span class="t">{text}</span></span>'


def fchip(big, small, cls="", cid=""):
    i = f' id="{cid}"' if cid else ""
    return f'<span class="fchip {cls}"{i}><b>{big}</b><small>{small}</small></span>'


