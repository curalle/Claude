"""Generate scenes.html + scenes.js for the convocation promo (video 4). Run before build.py."""
from pathlib import Path

HERE = Path(__file__).parent
RED = "#e0452b"
ARROW = f'<svg class="arr" width="110" height="60" viewBox="0 0 110 60"><path d="M6 30 H96 M72 8 L98 30 L72 52" fill="none" stroke="{RED}" stroke-width="10" stroke-linecap="round" stroke-linejoin="round" /></svg>'

# (id, start, end, label, normal price, promo price, said-at times: label, price)
COMBOS = [
    ("c1", 11.25, 16.5, "2 × 100g", 198, 129, 11.87, 13.76),
    ("c2", 16.5, 21.65, "2 × 50g", 158, 99, 17.14, 19.15),
    ("c3", 21.65, 26.25, "MIX COMBO", 178, 119, 21.92, 23.63),
]


def scene(sid, start, dur, kicker, inner):
    return f"""
      <div id="{sid}" class="scene clip" data-start="{start}" data-duration="{dur}" data-track-index="6">
        <div class="wipe"></div>
        <div class="panel">
          <div class="kick"><span>{kicker}</span><span class="rule"></span></div>
          {inner}
        </div>
      </div>
"""


html = """      <!-- Convocation promo panels (generated by make_scenes.py) -->
      <!-- Over footage (8.7–10.95s): "harga combo istimewa" -->
      <div id="promo" class="clip" data-start="8.7" data-duration="2.25" data-track-index="6">
        <span class="stamp" id="promo-in">Harga combo istimewa!</span>
      </div>
"""
js = (HERE / "helpers.js").read_text()
js += """      // Over footage — "harga combo istimewa"
      slam("#promo-in", 8.75, -5);
      tl.to("#promo", { opacity: 0, duration: 0.2, ease: "none" }, 10.7);
"""

for n, (cid, s, e, label, np, pp, t_lbl, t_price) in enumerate(COMBOS, 1):
    html += scene(cid, s, round(e - s + (0.45 if n < 3 else 0.45), 2), f"Combo istimewa · {n}/3 · Konvo UiTM", f"""<div class="combo" id="{cid}-lbl">{label}</div>
          <div class="np" id="{cid}-np"><span>Harga asal</span><span class="strike"><span class="x"></span>RM{np}</span></div>
          <div class="price" id="{cid}-pr"><span class="p"><span class="bar"></span><span class="t"><small>RM</small>{pp}</span></span></div>
          <div class="stampwrap" style="top: 1030px"><span class="stamp" id="{cid}-save">Jimat RM{np - pp}</span></div>""")
    js += f"""
      // Combo {n}: {label} RM{np} -> RM{pp}
      sceneIn("{cid}", {s});
      pop("#{cid}-lbl", {t_lbl}, 0.6);
      fadeUp("#{cid}-np", {round(t_lbl + 0.8, 2)});
      tl.fromTo("#{cid}-np .x", {{ scaleX: 0 }}, {{ scaleX: 1, duration: 0.3, ease: "power2.out" }}, {round(t_lbl + 1.2, 2)});
      slam("#{cid}-pr .p", {t_price}, -2);
      mark("#{cid}-pr .p", {round(t_price + 0.25, 2)});
      slam("#{cid}-save", {round(t_price + 0.9, 2)}, -6);
"""

html += scene("dt", 26.25, 5.15, "Tempoh tawaran", f"""<div class="hd" style="text-align: center">Tawaran sah</div>
          <div class="dates"><span class="cal" id="dt-a"><span class="m">OKT</span><span class="d">17</span></span><span id="dt-arr">{ARROW}</span><span class="cal" id="dt-b"><span class="m">NOV</span><span class="d">14</span></span></div>
          <div class="stampwrap" style="top: 900px"><span class="stamp" id="dt-only" style="font-size: 150px">Sahaja!</span></div>""")
js += """
      // Offer dates
      sceneIn("dt", 26.25);
      fadeUp("#dt .hd", 26.5);
      pop("#dt-a", 27.42, 0.5);
      tl.fromTo("#dt-arr", { opacity: 0, x: -30 }, { opacity: 1, x: 0, duration: 0.35, ease: "power3.out" }, 28.4);
      pop("#dt-b", 28.77, 0.5);
      slam("#dt-only", 29.77, -6);
      sceneOut("dt", 31.4);
"""

(HERE / "scenes.html").write_text(html)
(HERE / "scenes.js").write_text(js)
print("scenes written")
